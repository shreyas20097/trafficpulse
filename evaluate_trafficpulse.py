#!/usr/bin/env python3
"""
TrafficPulse multi-time evaluation runner.

Runs the existing trafficpulse_dynamic.py controller at selected TIRTL
timestamps, collects SUMO metrics, and compares the XGBoost source-stream
forecast against the actual next-15-minute TIRTL targets.

Usage from the project root:
    .venv/bin/python evaluate_trafficpulse.py

Outputs:
    artifacts/evaluation/trafficpulse_evaluation.csv
    artifacts/evaluation/trafficpulse_evaluation.json
"""

from __future__ import annotations

import csv
import json
import re
import subprocess
from pathlib import Path

import pandas as pd


PROJECT = Path(__file__).resolve().parent
DYNAMIC_SCRIPT = PROJECT / "trafficpulse_dynamic.py"
PYTHON = PROJECT / ".venv/bin/python"

FEATURE_FILE = PROJECT / "artifacts/tirtl_features.csv"
OUTPUT_DIR = PROJECT / "artifacts/evaluation"

# Use one January 2026 date consistently so the comparison is across
# different demand periods on the same day.
EVAL_DATE = "2026-01-17"

# Representative periods spanning the day.
EVAL_TIMES = [
    "06:30",
    "08:30",
    "10:45",
    "12:15",
    "14:30",
    "17:15",
    "18:45",
    "20:00",
]

# These are the same four independent TIRTL streams used by the controller.
# They are NOT four physical arms of one real intersection.
SOURCE_STREAMS = {
    "N": (133, "N"),
    "S": (126, "S"),
    "E": (147, "E"),
    "W": (195, "W"),
}

DIRECTION_SHARES = {
    "N": 0.2061,
    "S": 0.2034,
    "E": 0.2934,
    "W": 0.2971,
}


def load_features() -> pd.DataFrame:
    df = pd.read_csv(
        FEATURE_FILE,
        parse_dates=["datetime"],
        low_memory=False,
    )
    df["site"] = pd.to_numeric(df["site"], errors="coerce")
    df["heading"] = df["heading"].astype(str)
    return df


def get_stream_rows(df: pd.DataFrame, timestamp: pd.Timestamp) -> dict:
    details = {}

    for direction, (site, heading) in SOURCE_STREAMS.items():
        rows = df[
            (df["site"] == site)
            & (df["heading"] == heading)
            & (df["datetime"] == timestamp)
        ]

        if len(rows) != 1:
            raise RuntimeError(
                f"{direction}: expected exactly one feature row for "
                f"site={site}, heading={heading}, timestamp={timestamp}, "
                f"found {len(rows)}"
            )

        row = rows.iloc[0]

        actual = row["target_next_15min"]
        if pd.isna(actual):
            raise RuntimeError(
                f"{direction}: target_next_15min is unavailable "
                f"for {timestamp}"
            )

        current = float(row["total_motorized"])
        actual = float(actual)

        details[direction] = {
            "site": site,
            "heading": heading,
            "current": current,
            "actual_next_15": actual,
        }

    return details


def exact_allocate(total: int, shares: dict[str, float]) -> dict[str, int]:
    raw = {k: total * v for k, v in shares.items()}
    base = {k: int(v) for k, v in raw.items()}
    remainder = total - sum(base.values())

    ranked = sorted(
        shares,
        key=lambda k: raw[k] - base[k],
        reverse=True,
    )

    for k in ranked[:remainder]:
        base[k] += 1

    return base


def parse_controller_output(stdout: str) -> dict:
    patterns = {
        "representative_profile_veh_15min": r"Representative profile\s*:\s*([0-9.]+)",
        "current_source_total": r"Current source total\s*:\s*([0-9.]+)",
        "predicted_source_total": r"Predicted source total\s*:\s*([0-9.]+)",
        "forecast_multiplier": r"XGBoost multiplier\s*:\s*([0-9.]+)",
        "dynamic_intersection_veh_15min": r"Dynamic intersection\s*:\s*([0-9.]+)",
    }

    parsed = {}
    for name, pattern in patterns.items():
        m = re.search(pattern, stdout)
        if not m:
            raise RuntimeError(
                f"Could not parse '{name}' from controller output."
            )
        parsed[name] = float(m.group(1))

    m = re.search(r"N/S/E/W\s*:\s*(\{.*?\})", stdout)
    if m:
        # Safe because controller output is generated by our own script.
        direction_text = m.group(1)
        direction_text = (
            direction_text
            .replace("'", '"')
            .replace(" ", "")
        )
        parsed["direction_integer"] = json.loads(direction_text)

    m = re.search(
        r"Results:\s*(/home/[^\n]+\.results\.json)",
        stdout,
    )
    if not m:
        raise RuntimeError("Could not locate controller result JSON path.")

    parsed["results_file"] = Path(m.group(1))

    return parsed


def run_controller(date: str, time_str: str) -> tuple[dict, str]:
    tag = f"eval_{date.replace('-', '')}_{time_str.replace(':', '')}"

    cmd = [
        str(PYTHON),
        str(DYNAMIC_SCRIPT),
        "--date",
        date,
        "--time",
        time_str,
        "--tag",
        tag,
    ]

    proc = subprocess.run(
        cmd,
        cwd=PROJECT,
        text=True,
        capture_output=True,
    )

    if proc.returncode != 0:
        print(proc.stdout)
        print(proc.stderr)
        raise RuntimeError(
            f"TrafficPulse failed for {date} {time_str} "
            f"(exit code {proc.returncode})."
        )

    parsed = parse_controller_output(proc.stdout)

    result_file = parsed["results_file"]
    if not result_file.exists():
        raise RuntimeError(
            f"SUMO result JSON does not exist: {result_file}"
        )

    with result_file.open() as f:
        sumo_result = json.load(f)

    # trafficpulse_dynamic.py stores SUMO metrics under the
    # top-level "metrics" object.
    metrics = sumo_result.get("metrics", {})

    required_metrics = [
        "vehicles_reported",
        "vehicles_arrived",
        "vehicles_unfinished",
        "completion_rate_pct",
        "mean_travel_time_s",
        "mean_waiting_time_s",
        "mean_time_loss_s",
    ]

    missing = [
        key for key in required_metrics
        if key not in metrics or metrics[key] is None
    ]

    if missing:
        raise RuntimeError(
            f"SUMO result {result_file} is missing usable metrics: "
            + ", ".join(missing)
        )

    parsed["sumo_result"] = metrics
    return parsed, proc.stdout


def main() -> None:
    if not PROJECT.exists():
        raise SystemExit(
            f"Project directory not found: {PROJECT}"
        )

    required = [DYNAMIC_SCRIPT, PYTHON, FEATURE_FILE]
    missing = [str(p) for p in required if not p.exists()]
    if missing:
        raise SystemExit(
            "Missing required project files:\n" + "\n".join(missing)
        )

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    print("=" * 80)
    print("TRAFFICPULSE MULTI-TIME EVALUATION")
    print("=" * 80)
    print(f"Date: {EVAL_DATE}")
    print(f"Times: {', '.join(EVAL_TIMES)}")
    print()

    df = load_features()
    results = []

    for time_str in EVAL_TIMES:
        timestamp = pd.Timestamp(f"{EVAL_DATE} {time_str}")

        print("-" * 80)
        print(f"Running {timestamp}")

        streams = get_stream_rows(df, timestamp)

        actual_source_total = sum(
            d["actual_next_15"] for d in streams.values()
        )
        current_source_total = sum(
            d["current"] for d in streams.values()
        )

        controller, _stdout = run_controller(EVAL_DATE, time_str)

        predicted_source_total = controller[
            "predicted_source_total"
        ]

        # This is the directly comparable source-stream forecast error.
        source_abs_error = abs(
            predicted_source_total - actual_source_total
        )

        source_pct_error = (
            source_abs_error / actual_source_total * 100
            if actual_source_total > 0
            else 0.0
        )

        # Build an actual representative-intersection demand using the
        # exact same calibration logic used by TrafficPulse:
        #
        #     representative profile
        #       × actual_source_total/current_source_total
        #
        # This makes the forecast-vs-observed comparison comparable to the
        # demand that was actually sent into SUMO.
        actual_multiplier = (
            actual_source_total / current_source_total
            if current_source_total > 0
            else 0.0
        )

        actual_representative_demand = (
            controller["representative_profile_veh_15min"]
            * actual_multiplier
        )

        predicted_representative_demand = (
            controller["dynamic_intersection_veh_15min"]
        )

        representative_abs_error = abs(
            predicted_representative_demand
            - actual_representative_demand
        )

        representative_pct_error = (
            representative_abs_error
            / actual_representative_demand
            * 100
            if actual_representative_demand > 0
            else 0.0
        )

        sumo = controller["sumo_result"]

        row = {
            "date": EVAL_DATE,
            "time": time_str,
            "representative_profile_veh_15min": controller[
                "representative_profile_veh_15min"
            ],
            "current_source_total": current_source_total,
            "actual_source_total_next_15": actual_source_total,
            "predicted_source_total_next_15": predicted_source_total,
            "source_mae_abs_error": source_abs_error,
            "source_pct_error": source_pct_error,
            "actual_source_multiplier": actual_multiplier,
            "predicted_source_multiplier": controller[
                "forecast_multiplier"
            ],
            "actual_representative_demand_veh_15min": (
                actual_representative_demand
            ),
            "predicted_representative_demand_veh_15min": (
                predicted_representative_demand
            ),
            "representative_abs_error": representative_abs_error,
            "representative_pct_error": representative_pct_error,
            "sumo_vehicles": sumo.get("vehicles_reported"),
            "vehicles_arrived": sumo.get("vehicles_arrived"),
            "vehicles_unfinished": sumo.get("vehicles_unfinished"),
            "completion_rate_pct": sumo.get("completion_rate_pct"),
            "mean_travel_time_s": sumo.get("mean_travel_time_s"),
            "mean_waiting_time_s": sumo.get("mean_waiting_time_s"),
            "mean_time_loss_s": sumo.get("mean_time_loss_s"),
            "sumo_results_file": str(controller["results_file"]),
        }

        results.append(row)

        print(
            f"  Actual source next 15m : {actual_source_total:.2f}"
        )
        print(
            f"  Predicted source next 15m: {predicted_source_total:.2f}"
        )
        print(
            f"  Source error             : "
            f"{source_abs_error:.2f} ({source_pct_error:.2f}%)"
        )
        print(
            f"  Actual representative    : "
            f"{actual_representative_demand:.2f}"
        )
        print(
            f"  Predicted representative: "
            f"{predicted_representative_demand:.2f}"
        )
        print(
            f"  SUMO travel time         : "
            f"{sumo.get('mean_travel_time_s', 0):.2f}s"
        )
        print(
            f"  SUMO waiting time        : "
            f"{sumo.get('mean_waiting_time_s', 0):.2f}s"
        )

    out_csv = OUTPUT_DIR / "trafficpulse_evaluation.csv"
    out_json = OUTPUT_DIR / "trafficpulse_evaluation.json"

    fieldnames = list(results[0].keys())

    with out_csv.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(results)

    # Summary metrics for the eight evaluation points.
    source_actual = [
        r["actual_source_total_next_15"] for r in results
    ]
    source_pred = [
        r["predicted_source_total_next_15"] for r in results
    ]

    source_errors = [
        abs(a - p)
        for a, p in zip(source_actual, source_pred)
    ]

    representative_actual = [
        r["actual_representative_demand_veh_15min"]
        for r in results
    ]
    representative_pred = [
        r["predicted_representative_demand_veh_15min"]
        for r in results
    ]

    representative_errors = [
        abs(a - p)
        for a, p in zip(
            representative_actual,
            representative_pred,
        )
    ]

    summary = {
        "evaluation_date": EVAL_DATE,
        "evaluation_times": EVAL_TIMES,
        "n_scenarios": len(results),
        "source_stream_mae": sum(source_errors) / len(source_errors),
        "source_stream_rmse": (
            sum(
                (a - p) ** 2
                for a, p in zip(source_actual, source_pred)
            )
            / len(results)
        ) ** 0.5,
        "mean_source_pct_error": sum(
            r["source_pct_error"] for r in results
        ) / len(results),
        "representative_demand_mae": (
            sum(representative_errors)
            / len(representative_errors)
        ),
        "representative_demand_rmse": (
            sum(
                (a - p) ** 2
                for a, p in zip(
                    representative_actual,
                    representative_pred,
                )
            )
            / len(results)
        ) ** 0.5,
        "mean_representative_pct_error": sum(
            r["representative_pct_error"] for r in results
        ) / len(results),
        "mean_travel_time_s": sum(
            r["mean_travel_time_s"] for r in results
        ) / len(results),
        "mean_waiting_time_s": sum(
            r["mean_waiting_time_s"] for r in results
        ) / len(results),
        "mean_time_loss_s": sum(
            r["mean_time_loss_s"] for r in results
        ) / len(results),
        "all_runs_completed": all(
            r["completion_rate_pct"] == 100.0
            and r["vehicles_unfinished"] == 0
            for r in results
        ),
    }

    with out_json.open("w") as f:
        json.dump(
            {
                "summary": summary,
                "runs": results,
            },
            f,
            indent=2,
        )

    print()
    print("=" * 80)
    print("EVALUATION COMPLETE")
    print("=" * 80)
    print(f"Runs completed: {len(results)}")
    print(f"Source MAE: {summary['source_stream_mae']:.2f}")
    print(f"Source RMSE: {summary['source_stream_rmse']:.2f}")
    print(
        f"Mean source percentage error: "
        f"{summary['mean_source_pct_error']:.2f}%"
    )
    print(
        f"Representative-demand MAE: "
        f"{summary['representative_demand_mae']:.2f}"
    )
    print(
        f"Representative-demand RMSE: "
        f"{summary['representative_demand_rmse']:.2f}"
    )
    print(
        f"Mean representative percentage error: "
        f"{summary['mean_representative_pct_error']:.2f}%"
    )
    print(f"All SUMO runs completed: {summary['all_runs_completed']}")
    print()
    print(f"CSV : {out_csv}")
    print(f"JSON: {out_json}")


if __name__ == "__main__":
    main()
